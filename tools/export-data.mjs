import { DatabaseSync } from "node:sqlite";
import { mkdir, open, writeFile, rm, stat } from "node:fs/promises";
import { createWriteStream } from "node:fs";
import { pipeline } from "node:stream/promises";
import { Transform } from "node:stream";
import { createHash } from "node:crypto";
import { resolve, join } from "node:path";
import { createLocalFileStore } from "../file-store.mjs";
const [target, ...extra] = process.argv.slice(2);
if (target === "--help") {
  console.log(
    "Usage: npm run export-data -- <new private output directory>\nSource: PINGO_DB_PATH and PINGO_UPLOAD_DIR. Exports JSONL, PostgreSQL SQL and file blobs. Sessions are omitted. Contains private account/chat/report data; do not commit or publish.",
  );
  process.exit(0);
}
let db,
  created = false;
const output = target ? resolve(target) : null;
const ident = (value) => '"' + value.replaceAll('"', '""') + '"';
function literal(value) {
  if (value === null) return "NULL";
  if (typeof value === "number") {
    if (!Number.isSafeInteger(value)) throw Error("Unsafe integer in export");
    return String(value);
  }
  if (typeof value !== "string" || value.includes("\0"))
    throw Error(
      "PostgreSQL cannot represent this SQLite value (BLOB/NUL). Source data was not changed.",
    );
  return "'" + value.replaceAll("'", "''") + "'";
}
function checks(sql) {
  const result = [];
  const pattern = /\bCHECK\s*\(/gi;
  let match;
  while ((match = pattern.exec(sql))) {
    let depth = 1,
      quote = null,
      end = pattern.lastIndex;
    for (; end < sql.length && depth; end++) {
      const char = sql[end];
      if (quote) {
        if (char === quote) {
          if (sql[end + 1] === quote) end++;
          else quote = null;
        }
      } else if (char === "'" || char === '"') quote = char;
      else if (char === "(") depth++;
      else if (char === ")") depth--;
    }
    if (depth) throw Error("Unbalanced schema CHECK");
    result.push("CHECK (" + sql.slice(pattern.lastIndex, end - 1) + ")");
    pattern.lastIndex = end;
  }
  return result;
}
try {
  if (!output || extra.length)
    throw Error(
      "새 비공개 출력 폴더 하나를 지정하세요. --help로 사용법을 확인하세요.",
    );
  const source = resolve(
    process.env.PINGO_DB_PATH ||
      new URL("../.data/pingo.sqlite", import.meta.url).pathname,
  );
  await stat(source);
  db = new DatabaseSync(source, { readOnly: true });
  db.exec("BEGIN;");
  const tables = db
    .prepare(
      "SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'  ORDER BY name",
    )
    .all();
  if (!tables.some((table) => table.name === "users"))
    throw Error("Pingo 데이터베이스가 아닙니다.");
  await mkdir(output, { mode: 0o700 });
  created = true;
  await mkdir(join(output, "tables"), { mode: 0o700 });
  await mkdir(join(output, "files"), { mode: 0o700 });
  const sql = await open(join(output, "postgres.sql"), "wx", 0o600);
  const manifest = {
    format: "pingo-export",
    version: 1,
    created_at: new Date().toISOString(),
    omitted_data_tables: ["sessions"],
    tables: [],
    files: [],
  };
  const constraints = [],
    indexes = [],
    identities = [];
  try {
    await sql.writeFile(
      "-- Private Pingo export. Import into an EMPTY PostgreSQL database.\nBEGIN;\nSET LOCAL standard_conforming_strings = on;\n",
    );
    for (const table of tables) {
      if (!/^[a-z][a-z0-9_]*$/.test(table.name))
        throw Error("Unsupported table name in export");
      const columns = db
          .prepare("PRAGMA table_info(" + ident(table.name) + ")")
          .all(),
        primary = columns.filter((c) => c.pk).sort((a, b) => a.pk - b.pk);
      const defs = columns.map((column) => {
        const type = column.type.toUpperCase();
        if (!["TEXT", "INTEGER"].includes(type))
          throw Error("Unsupported source column type: " + type);
        const identity =
          type === "INTEGER" && primary.length === 1 && column.pk;
        if (identity)
          identities.push({ table: table.name, column: column.name });
        return (
          ident(column.name) +
          " " +
          (type === "INTEGER" ? "BIGINT" : "TEXT") +
          (identity ? " GENERATED BY DEFAULT AS IDENTITY" : "") +
          (column.notnull ? " NOT NULL" : "") +
          (column.dflt_value !== null ? " DEFAULT " + column.dflt_value : "")
        );
      });
      if (primary.length)
        defs.push(
          "PRIMARY KEY (" + primary.map((c) => ident(c.name)).join(",") + ")",
        );
      defs.push(...checks(table.sql));
      await sql.writeFile(
        "CREATE TABLE " +
          ident(table.name) +
          " (\n  " +
          defs.join(",\n  ") +
          "\n);\n",
      );
      const keys = db
        .prepare("PRAGMA foreign_key_list(" + ident(table.name) + ")")
        .all();
      for (const id of new Set(keys.map((key) => key.id))) {
        const parts = keys
          .filter((key) => key.id === id)
          .sort((a, b) => a.seq - b.seq);
        constraints.push(
          "ALTER TABLE " +
            ident(table.name) +
            " ADD CONSTRAINT " +
            ident(table.name + "_fk_" + id) +
            " FOREIGN KEY (" +
            parts.map((key) => ident(key.from)).join(",") +
            ") REFERENCES " +
            ident(parts[0].table) +
            " (" +
            parts.map((key) => ident(key.to)).join(",") +
            ") ON DELETE " +
            parts[0].on_delete +
            " ON UPDATE " +
            parts[0].on_update +
            ";\n",
        );
      }
      for (const [n, index] of db
        .prepare("PRAGMA index_list(" + ident(table.name) + ")")
        .all()
        .entries()) {
        if (index.origin === "pk") continue;
        const saved = db
          .prepare(
            "SELECT sql FROM sqlite_master WHERE type='index' AND name=?",
          )
          .get(index.name)?.sql;
        if (saved) indexes.push(saved + ";\n");
        else if (index.unique) {
          const parts = db
            .prepare("PRAGMA index_info(" + ident(index.name) + ")")
            .all();
          indexes.push(
            "CREATE UNIQUE INDEX " +
              ident("pingo_" + table.name + "_unique_" + n) +
              " ON " +
              ident(table.name) +
              " (" +
              parts.map((part) => ident(part.name)).join(",") +
              ");\n",
          );
        }
      }
      const file = await open(
        join(output, "tables", table.name + ".jsonl"),
        "wx",
        0o600,
      );
      let count = 0;
      try {
        for (const row of table.name === "sessions"
          ? []
          : db.prepare("SELECT * FROM " + ident(table.name)).iterate()) {
          await file.writeFile(JSON.stringify(row) + "\n");
          await sql.writeFile(
            "INSERT INTO " +
              ident(table.name) +
              " (" +
              columns.map((c) => ident(c.name)).join(",") +
              ") VALUES (" +
              columns.map((c) => literal(row[c.name])).join(",") +
              ");\n",
          );
          count++;
        }
      } finally {
        await file.close();
      }
      manifest.tables.push({
        name: table.name,
        count,
        columns,
        foreign_keys: keys,
      });
    }
    for (const statement of indexes) await sql.writeFile(statement);
    for (const statement of constraints) await sql.writeFile(statement);
    for (const item of identities)
      await sql.writeFile(
        "SELECT setval(pg_get_serial_sequence(" +
          literal(ident(item.table)) +
          "," +
          literal(item.column) +
          "), COALESCE((SELECT max(" +
          ident(item.column) +
          ") FROM " +
          ident(item.table) +
          "),1), EXISTS(SELECT 1 FROM " +
          ident(item.table) +
          "));\n",
      );
    await sql.writeFile("COMMIT;\n");
  } finally {
    await sql.close();
  }
  const storage = createLocalFileStore(
    process.env.PINGO_UPLOAD_DIR ||
      new URL("../.data/uploads", import.meta.url).pathname,
  );
  if (tables.some((table) => table.name === "attachments"))
    for (const file of db.prepare("SELECT * FROM attachments").iterate()) {
      const opened = await storage.open(file.storage_key),
        hash = createHash("sha256");
      let bytes = 0;
      const checksum = new Transform({
        transform(chunk, encoding, callback) {
          bytes += chunk.length;
          hash.update(chunk);
          callback(null, chunk);
        },
      });
      await pipeline(
        opened.stream,
        checksum,
        createWriteStream(join(output, "files", file.storage_key), {
          flags: "wx",
          mode: 0o600,
        }),
      );
      if (bytes !== file.size || hash.digest("hex") !== file.sha256)
        throw Error("Attachment checksum mismatch: " + file.id);
      manifest.files.push({
        attachment_id: file.id,
        storage_key: file.storage_key,
        size: file.size,
        sha256: file.sha256,
      });
    }
  await writeFile(
    join(output, "manifest.json"),
    JSON.stringify(manifest, null, 2) + "\n",
    { flag: "wx", mode: 0o600 },
  );
  db.exec("COMMIT;");
  console.log(
    `내보내기 완료: ${manifest.tables.length}개 테이블, ${manifest.files.length}개 파일. 로그인 세션은 제외했습니다. 출력 폴더를 비공개로 보관하세요.`,
  );
} catch (error) {
  if (db) {
    try {
      db.exec("ROLLBACK;");
    } catch {}
  }
  if (created) await rm(output, { recursive: true, force: true });
  console.error(
    "내보내기 실패: " + String(error.message).replace(/[\x00-\x1f\x7f]/g, "?"),
  );
  process.exitCode = 1;
} finally {
  db?.close();
}
